#!/usr/bin/env node
// Writes a small FAKE "vibe-coded" Next.js + Supabase + Stripe app for demos and tests.
// All keys are fake and are assembled at runtime so this repo never contains secret-shaped strings.
// Usage: node examples/make-demo-app.mjs <dir> [--fixed]
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const fake = (prefix, n) => prefix + 'DEMOFAKE'.repeat(8).slice(0, n);

export function makeDemoApp(dir, { fixed = false, git = true } = {}) {
  const root = resolve(dir);
  const w = (rel, body) => { const p = join(root, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body); };
  w('package.json', JSON.stringify({
    name: 'demo-founder-app', private: true, scripts: { dev: 'next dev', build: 'next build' },
    dependencies: { next: '15.0.0', react: '19.0.0', '@supabase/supabase-js': '2.45.0', stripe: '16.0.0',
      ...(fixed ? { '@upstash/ratelimit': '2.0.0', '@sentry/nextjs': '8.0.0' } : {}) },
  }, null, 2));
  w('README.md', '# demo-founder-app\nFake demo app generated by BlitzHash Senior Engineer Skills. Not a real product.\n');
  w('.gitignore', fixed ? 'node_modules\n.next\n.env*\n!.env.example\n' : 'node_modules\n.next\n');
  w('.env.example', 'NEXT_PUBLIC_SUPABASE_URL=\nNEXT_PUBLIC_SUPABASE_ANON_KEY=\nSUPABASE_SERVICE_ROLE_KEY=\nSTRIPE_SECRET_KEY=\nSTRIPE_WEBHOOK_SECRET=\n');
  if (!fixed) {
    w('.env', `NEXT_PUBLIC_SUPABASE_URL=https://demo.supabase.example\nNEXT_PUBLIC_SUPABASE_SERVICE_ROLE_KEY=demo-not-a-real-key\nNEXT_PUBLIC_OPENAI_API_KEY=demo-not-a-real-key\n`);
  }
  w('next.config.mjs', fixed
    ? `const securityHeaders = [\n  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },\n  { key: 'X-Frame-Options', value: 'DENY' },\n  { key: 'X-Content-Type-Options', value: 'nosniff' },\n  { key: 'Content-Security-Policy', value: "default-src 'self'; frame-ancestors 'none'" },\n];\nexport default { async headers() { return [{ source: '/(.*)', headers: securityHeaders }]; } };\n`
    : `export default { productionBrowserSourceMaps: true };\n`);
  w('lib/stripe.ts', fixed
    ? `import Stripe from 'stripe';\nexport const stripe = new Stripe(process.env.STRIPE_SECRET_KEY!);\n`
    : `import Stripe from 'stripe';\nexport const stripe = new Stripe('${fake('sk_' + 'live_', 28)}');\n`);
  w('components/AdminTable.tsx', fixed
    ? `'use client';\nimport { createClient } from '@supabase/supabase-js';\nexport const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!);\n`
    : `'use client';\nimport { createClient } from '@supabase/supabase-js';\n// TODO: make this work for the admin page\nexport const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_SERVICE_ROLE_KEY!);\n`);
  w('app/api/chat/route.ts', fixed
    ? `import { Ratelimit } from '@upstash/ratelimit';\nimport { createServerClient } from '@/lib/supabase-server';\nexport async function POST(req: Request) {\n  const { data: { user } } = await createServerClient().auth.getUser();\n  if (!user) return new Response('Unauthorized', { status: 401 });\n  // ratelimit.limit(user.id) before calling the model\n  return Response.json({ ok: true });\n}\n`
    : `export async function POST(req: Request) {\n  const { prompt } = await req.json();\n  const r = await fetch('https://api.openai.example/v1/chat', { method: 'POST', headers: { Authorization: 'Bearer ' + process.env.NEXT_PUBLIC_OPENAI_API_KEY }, body: JSON.stringify({ prompt }) });\n  return new Response(r.body, { headers: { 'Access-Control-Allow-Origin': '*' } });\n}\n`);
  w('app/api/users/route.ts', fixed
    ? `import { createServerClient } from '@/lib/supabase-server';\nexport async function GET() {\n  const { data: { user } } = await createServerClient().auth.getUser();\n  if (!user) return new Response('Unauthorized', { status: 401 });\n  return Response.json({ id: user.id });\n}\n`
    : `import { supabase } from '@/components/AdminTable';\nexport async function GET() {\n  const { data } = await supabase.from('users').select('*');\n  return Response.json(data);\n}\n`);
  w('app/api/webhooks/stripe/route.ts', fixed
    ? `import { stripe } from '@/lib/stripe';\nexport async function POST(req: Request) {\n  const body = await req.text();\n  const event = stripe.webhooks.constructEvent(body, req.headers.get('stripe-signature')!, process.env.STRIPE_WEBHOOK_SECRET!);\n  return Response.json({ received: event.type });\n}\n`
    : `import { stripe } from '@/lib/stripe';\nexport async function POST(req: Request) {\n  const event = await req.json(); // trust the payload\n  if (event.type === 'checkout.session.completed') { /* mark user as paid */ }\n  return Response.json({ received: true });\n}\n`);
  if (fixed) {
    w('sentry.server.config.ts', `import * as Sentry from '@sentry/nextjs';\nSentry.init({ dsn: process.env.SENTRY_DSN });\n`);
    w('docs/backup-restore.md', '# Backups\nDaily pg_dump to object storage, 14 days kept. Restore drill: restore into a scratch database monthly and time it.\n');
    w('package-lock.json', '{}\n');
  }
  if (git) {
    try {
      execFileSync('git', ['init', '-q'], { cwd: root });
      execFileSync('git', ['add', '-A'], { cwd: root });
    } catch { /* git is optional */ }
  }
  return root;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dir = process.argv[2];
  if (!dir) { console.error('usage: node examples/make-demo-app.mjs <dir> [--fixed]'); process.exit(2); }
  console.log(`Fake demo app written to ${makeDemoApp(dir, { fixed: process.argv.includes('--fixed') })}`);
}
